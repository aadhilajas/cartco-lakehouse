import {chromium} from 'playwright';
import {spawn} from 'node:child_process';
import {mkdir,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import net from 'node:net';
import assert from 'node:assert/strict';
const args=Object.fromEntries(process.argv.slice(2).reduce((a,v,i,all)=>{if(v.startsWith('--'))a.push([v.slice(2),all[i+1]]);return a},[]));
if(!args.python||!args.snapshot||!args.output)throw new Error('--python, --snapshot and --output are required');
const repo=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const probe=net.createServer();await new Promise(resolve=>probe.listen(0,'127.0.0.1',resolve));const port=probe.address().port;await new Promise(resolve=>probe.close(resolve));
const server=spawn(path.resolve(args.python),[path.join(repo,'scripts/serve_dashboard.py'),'--dist',path.join(repo,'dashboard/dist'),'--snapshot',path.resolve(args.snapshot),'--port',String(port)],{cwd:repo,windowsHide:true,stdio:['ignore','pipe','pipe']});
let logs='';server.stdout.on('data',x=>logs+=x);server.stderr.on('data',x=>logs+=x);
let browser;
try{
 let ready=false;for(let i=0;i<80;i++){try{const r=await fetch(`http://127.0.0.1:${port}/health`);if(r.ok){ready=true;break}}catch{}await new Promise(r=>setTimeout(r,250))}assert(ready,logs);
 browser=await chromium.launch({headless:true,...(args.chrome?{executablePath:args.chrome}:{})});
 const page=await browser.newPage({viewport:{width:1440,height:1100},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(`http://127.0.0.1:${port}`,{waitUntil:'networkidle'});
 await page.getByText('Commerce, reconciled.',{exact:true}).waitFor();
 await page.locator('.release-strip, [role=alert]').first().waitFor();
 assert(await page.locator('.release-strip').count(),await page.locator('body').innerText());
 assert((await page.locator('.metric strong').first().textContent()).includes('921.75'));
 await mkdir(args.output,{recursive:true});
 await page.screenshot({path:path.join(args.output,'dashboard-business.png'),fullPage:true});
 await page.locator('select').selectOption('shopify');
 assert.equal(await page.locator('.metric strong').first().textContent(),'₹301.50');
 await page.getByRole('button',{name:'Reset filters'}).click();
 await page.getByRole('button',{name:'Engineering',exact:true}).click();
 assert.equal(await page.locator('.metric strong').first().textContent(),'Passed');
 assert.equal(await page.locator('.suite').count(),7);
 await page.screenshot({path:path.join(args.output,'dashboard-engineering.png'),fullPage:true});
 await page.getByRole('button',{name:'Lineage',exact:true}).click();
 await page.getByText('Marquez backend verification is recorded.',{exact:false}).waitFor();
 assert.equal(await page.locator('tbody tr').count(),44);
 await page.screenshot({path:path.join(args.output,'dashboard-lineage.png'),fullPage:true});
 await page.getByRole('button',{name:'Business',exact:true}).click();
 await page.setViewportSize({width:390,height:844});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:path.join(args.output,'dashboard-mobile.png'),fullPage:true});
 await page.route('**/api/snapshot',route=>route.fulfill({status:200,contentType:'application/json',body:'{"schema_version":999}'}));
 await page.getByRole('button',{name:'Refresh snapshot'}).click();
 await page.getByRole('alert').waitFor();
 assert((await page.getByRole('alert').textContent()).includes('Keeping the last valid snapshot'));
 assert.equal(await page.locator('.metric strong').first().textContent(),'₹921.75');
 const response=await fetch(`http://127.0.0.1:${port}/api/run`,{method:'POST'});assert.equal(response.status,405);
 const traversal=await fetch(`http://127.0.0.1:${port}/%2e%2e/%2e%2e/.env`);assert.equal(traversal.status,404);
 assert.deepEqual(errors,[]);
 await writeFile(path.join(args.output,'ui-verification.json'),JSON.stringify({business_total_inr:'921.75',shopify_filter_inr:'301.50',quality_suites:7,lineage_fields:44,mobile_no_page_overflow:true,bad_refresh_retains_snapshot:true,write_endpoint_refused:true,traversal_refused:true,browser_errors:errors},null,2));
 console.log('Dashboard browser acceptance passed');
}finally{if(browser)await browser.close();server.kill();}
